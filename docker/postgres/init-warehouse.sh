#!/bin/bash
# Creates the warehouse database and its schemas.
# Postgres runs this once, on first start with an empty volume.
set -e

psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" <<SQL
CREATE USER $WAREHOUSE_USER WITH PASSWORD '$WAREHOUSE_PASSWORD';
CREATE DATABASE $WAREHOUSE_DB OWNER $WAREHOUSE_USER;
SQL

psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$WAREHOUSE_DB" <<SQL
CREATE SCHEMA raw AUTHORIZATION $WAREHOUSE_USER;
CREATE SCHEMA marts AUTHORIZATION $WAREHOUSE_USER;
CREATE SCHEMA meta AUTHORIZATION $WAREHOUSE_USER;
SQL
